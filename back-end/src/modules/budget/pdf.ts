/** Babel `LOCALE_BY_LANG` : langue UI → locale monétaire. */
const LOCALE_BY_LANG: Record<string, string> = {
  es: 'es_ES',
  en: 'en_US',
  ta: 'en_IN',
  te: 'en_IN',
  hi: 'hi_IN',
  fr: 'fr_FR',
  pt: 'pt_PT',
  'pt-BR': 'pt_BR',
  de: 'de_DE',
  hu: 'hu_HU',
  pl: 'pl_PL',
  it: 'it_IT',
  ar: 'ar',
};

const currencyDisplayCache = new Map<string, CurrencyDisplay>();

/**
 * Format monétaire localisé (`babel.numbers.format_currency` via Intl).
 * `currencyDisplay` suit la devise : code ASCII en tête (« EUR ») pour les
 * devises non-euro, symbole pour EUR/USD/GBP — approximation documentée.
 */
type CurrencyDisplay = 'symbol' | 'code' | 'name';

function currencyDisplay(currency: string, moneyLocale: string): CurrencyDisplay {
  const key = `${currency}:${moneyLocale}`;
  const cached = currencyDisplayCache.get(key);
  if (cached) return cached;
  const fallback: CurrencyDisplay = ['EUR', 'USD', 'GBP'].includes(currency) ? 'symbol' : 'code';
  try {
    new Intl.NumberFormat(moneyLocale.replace('_', '-'), {
      style: 'currency',
      currency,
      currencyDisplay: 'symbol',
    }).format(1);
    currencyDisplayCache.set(key, 'symbol');
    return 'symbol';
  } catch {
    currencyDisplayCache.set(key, fallback);
    return fallback;
  }
}

/** Montant en centimes → chaîne localisée (ex. `1.234,56 €`). */
export function formatCurrencyCents(
  cents: number,
  currency: string,
  locale: string,
  fallbackSymbol = '€',
): string {
  const moneyLocale = LOCALE_BY_LANG[locale] ?? 'es_ES';
  const amount = Number(centsToDecimalString(cents));
  try {
    return new Intl.NumberFormat(moneyLocale.replace('_', '-'), {
      style: 'currency',
      currency,
      currencyDisplay: currencyDisplay(currency, moneyLocale),
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }).format(amount);
  } catch {
    return `${centsToDecimalString(cents)} ${fallbackSymbol}`.trim();
  }
}

