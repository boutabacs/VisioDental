function labelsFor(locale: string): DigestLabels {
  const base = locale.split('-')[0]!.toLowerCase();
  return LABELS[base as keyof typeof LABELS] ?? LABELS.en;
}

function formatClock(iso: string): string {
  const time = iso.slice(11, 16);
  return /^\d{2}:\d{2}$/.test(time) ? time : iso;
}

function formatDay(now: Date, locale: string, timeZone: string): string {
  try {
    return new Intl.DateTimeFormat(locale, { dateStyle: 'full', timeZone }).format(now);
  } catch {
    return toZonedIso(now, timeZone).slice(0, 10);
  }
}

export interface DigestSummary {
  date: string;
  appointmentsTotal: number;
  appointments: { time: string; patient: string | null; status: string }[];
  overdueRecalls: number;
  budgetsAwaitingReply: number;
}

export async function buildDigestSummary(
  clinicId: string,
  timeZone: string,
  now: Date,
): Promise<DigestSummary> {
  const date = toZonedIso(now, timeZone).slice(0, 10);
  const { rows, total } = await agendaService.listAppointments(clinicId, timeZone, {
    startDate: `${date}T00:00:00`,
    endDate: `${date}T23:59:59.999`,
    page: 1,
    pageSize: 200,
    order: 'asc',
  });
  const overdue = await listRecalls(clinicId, { overdue: true }, 1, 1);
  const budgetsAwaitingReply = await prisma.budgets.count({
    where: { clinic_id: clinicId, status: 'sent' },
  });
  return {
    date,
    appointmentsTotal: total,
    appointments: rows.map((row) => ({
      time: formatClock(row.start_time),
      patient: row.patient
        ? `${row.patient.first_name} ${row.patient.last_name}`
        : null,
      status: row.status,
    })),
    overdueRecalls: overdue.total,
    budgetsAwaitingReply,
  };
}

export function renderDigestText(
  summary: DigestSummary,
  options: { clinicName: string; locale: string; now: Date; timeZone: string },
): { subject: string; text: string } {
  const labels = labelsFor(options.locale);
  const lines: string[] = [`${options.clinicName} — ${labels.subject}`, formatDay(options.now, options.locale, options.timeZone), ''];

  const shown = summary.appointments.slice(0, 12);
  const hidden = Math.max(0, summary.appointments.length - shown.length);
  lines.push(`${labels.appointments}: ${summary.appointmentsTotal}`);
  if (shown.length === 0) {
    lines.push(`  ${labels.none}`);
  } else {
    for (const appointment of shown) {
      const status = labels.statuses[appointment.status] ?? appointment.status;
      const patient = appointment.patient ?? '—';
      lines.push(`  · ${appointment.time} ${patient} (${status})`);
    }
    if (hidden > 0) lines.push(`  ${labels.more(hidden)}`);
  }
  lines.push('', `${labels.recalls}: ${summary.overdueRecalls}`, `${labels.budgets}: ${summary.budgetsAwaitingReply}`, '');
  const localTime = toZonedIso(options.now, options.timeZone).slice(11, 16);
  lines.push(labels.footer(options.clinicName, localTime));

  return {
    subject: `${options.clinicName} — ${labels.subject}`,
    text: lines.join('\n'),
  };
}

export interface DigestResult {
  sent: number;
  skipped: number;
}

/** Une passe : cabinets dont l'heure locale correspond à `digest_hour`. */
export async function processMorningDigests(now: Date = new Date()): Promise<DigestResult> {
  let sent = 0;
  let skipped = 0;
  const settingsRows = await prisma.copilot_settings.findMany({ where: { digest_enabled: true } });
  for (const settings of settingsRows) {
    try {
      const clinic = await prisma.clinics.findUnique({
        where: { id: settings.clinic_id },
        select: { name: true, timezone: true },
      });
      if (!clinic) continue;
      const timeZone = clinic.timezone || 'UTC';
      const local = toZonedIso(now, timeZone);
      const hour = Number(local.slice(11, 13));
      if (hour !== settings.digest_hour) continue;

      const wanted = recipientIds(settings);
      if (wanted.length === 0) continue;
      const members = await prisma.clinic_memberships.findMany({
        where: {
          clinic_id: settings.clinic_id,
          user_id: { in: wanted },
          users: { is_active: true },
        },
        select: {
          user_id: true,
          users: { select: { email: true, first_name: true } },
        },
      });
      if (members.length === 0) continue;

      const locale = await resolveClinicCommunicationLocale(settings.clinic_id);
      const summary = await buildDigestSummary(settings.clinic_id, timeZone, now);
      const rendered = renderDigestText(summary, {
        clinicName: clinic.name,
        locale,
        now,
        timeZone,
      });
      const date = summary.date;

      for (const member of members) {
        const message = await enqueue({
          clinicId: settings.clinic_id,
          notificationType: 'daily_digest',
          context: { digest_date: date },
          toAddress: member.users.email,
          channels: ['email'],
          messageKind: 'session',
          bodyText: rendered.text,
          subject: rendered.subject,
          forceSend: true,
          triggeredByEvent: 'scheduler.daily_digest',
          dedupKey: `daily_digest:${settings.clinic_id}:${date}:${member.user_id}`,
        });
        if (message === null || message.status === 'skipped') skipped += 1;
        else sent += 1;
      }
      console.info(
        `[notifications] Daily digest queued for ${settings.clinic_id}: ${sent} message(s)`,
      );
    } catch (error) {
      console.error(
        `[notifications] Daily digest failed for clinic ${settings.clinic_id}:`,
        error,
      );
    }
  }
  return { sent, skipped };
}

